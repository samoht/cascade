let write_jobs file ~envs ~media ~nested ~supports ~hosts_json ~container =
  let oc = open_out file in
  output_string oc
    (Json.to_string
       (Json.Obj
          [
            ("envs", Json.Arr envs);
            ("media", Json.Arr media);
            ("nested", Json.Arr nested);
            ("supports", Json.Arr supports);
            ("hosts", Json.Arr hosts_json);
            ("container", Json.Arr container);
          ]));
  close_out oc

let () =
  parse_args ();
  check_judge ();

  (* --- the media population, and every rewrite of it --- *)
  let media_ids : (string, string) Hashtbl.t = Hashtbl.create 4096 in
  let media_by_id : (string, media_job) Hashtbl.t = Hashtbl.create 4096 in
  let order = ref [] in
  let counter = ref 0 in
  let intern text =
    match Hashtbl.find_opt media_ids text with
    | Some id -> Some id
    | None ->
        if not (writable_media text) then None
        else (
          incr counter;
          let id = string_of_int !counter in
          Hashtbl.replace media_ids text id;
          Hashtbl.replace media_by_id id { id; text; query = parse_media text };
          order := id :: !order;
          Some id)
  in
  let seed_ids =
    List.filter_map intern
      (List.sort_uniq String.compare
         (List.filter selected
            (List.filter writable_media (media_seeds ~seed:!seed))))
  in
  (* A rewrite is compared against the stage it was derived from: the parser's
     own serialisation against the source text, and each rewrite against that
     serialisation. *)
  let rewrite_pairs =
    List.concat_map
      (fun id ->
        let job = Hashtbl.find media_by_id id in
        let stages = rewrites_of job.query in
        let base =
          match
            List.find_map
              (fun (label, text) ->
                if String.equal label "round_trip" then Some text else None)
              stages
          with
          | Some text -> ( match intern text with Some r -> r | None -> id)
          | None -> id
        in
        List.filter_map
          (fun (label, text) ->
            let from = if String.equal label "round_trip" then id else base in
            match intern text with
            | Some rewritten when not (String.equal rewritten from) ->
                Some (label, from, rewritten)
            | Some _ | None -> None)
          stages)
      seed_ids
  in
  let media_jobs =
    List.rev_map (fun id -> Hashtbl.find media_by_id id) !order
  in
  let media_text id =
    match Hashtbl.find_opt media_by_id id with Some j -> j.text | None -> id
  in

  (* --- the supports population --- *)
  let supports_ids : (string, string) Hashtbl.t = Hashtbl.create 512 in
  let supports_order = ref [] in
  let supports_counter = ref 0 in
  let intern_supports text =
    match Hashtbl.find_opt supports_ids text with
    | Some id -> Some id
    | None ->
        if not (writable text) then None
        else (
          incr supports_counter;
          let id = string_of_int !supports_counter in
          Hashtbl.replace supports_ids text id;
          supports_order := (id, text) :: !supports_order;
          Some id)
  in
  (* The leaves are what the browser's answers build the supports table out of,
     so [--only] narrows the compounds and never the table: a table missing a
     leaf answers false about it and every compound over it. *)
  let supports_texts =
    List.sort_uniq String.compare
      (List.filter
         (fun t -> selected t || List.exists (String.equal t) supports_leaves)
         (List.filter writable (supports_seeds ~seed:!seed)))
  in
  List.iter (fun t -> ignore (intern_supports t)) supports_texts;

  (* [simplify_under] decides a guard against the conjunction enclosing it, and
     the decision it returns is itself a condition the browser has to answer
     about, so it joins the population before the browser is asked. *)
  let simplify_sample = ref [] in
  let pool = Array.of_list supports_texts in
  let s = stream (!seed + 15485863) in
  if Array.length pool > 1 then
    for _ = 1 to 600 do
      let k = pool.(next s mod Array.length pool) in
      let c = pool.(next s mod Array.length pool) in
      match (parse_supports k, parse_supports c) with
      | Some kc, Some cc -> (
          match Supports.simplify_under ~context:[ kc ] cc with
          | exception _ -> ()
          | decision ->
              (match decision with
              | `Cond c' -> (
                  match Supports.to_string c' with
                  | exception _ -> ()
                  | text -> ignore (intern_supports text))
              | `True | `False -> ());
              simplify_sample := (k, c, decision) :: !simplify_sample)
      | _ -> ()
    done;
  let supports_jobs = List.rev !supports_order in

  (* --- the container population --- *)
  let container_texts =
    List.sort_uniq String.compare
      (List.filter selected (List.filter writable container_seeds))
  in
  let container_jobs =
    ref (List.mapi (fun i t -> (string_of_int i, t)) container_texts)
  in
  let container_id text =
    List.find_map
      (fun (id, t) -> if String.equal t text then Some id else None)
      !container_jobs
  in
  let intern_container text =
    match container_id text with
    | Some id -> Some id
    | None ->
        if not (writable text) then None
        else
          let id = string_of_int (List.length !container_jobs) in
          container_jobs := !container_jobs @ [ (id, text) ];
          Some id
  in
  let container_rewrites =
    List.filter_map
      (fun (id, text) ->
        match parse_container text with
        | None -> None
        | Some c -> (
            match
              Container.to_stylesheet_string ~minify:true
                (Container.lower_for_minify c)
            with
            | exception _ -> None
            | rewritten -> (
                if String.equal rewritten text then None
                else
                  match intern_container rewritten with
                  | Some rid when not (String.equal rid id) ->
                      Some (id, rid, rewritten)
                  | Some _ | None -> None)))
      (List.map (fun (id, t) -> (id, t)) !container_jobs)
  in
  let container_text id =
    match List.find_opt (fun (i, _) -> String.equal i id) !container_jobs with
    | Some (_, t) -> t
    | None -> id
  in

  (* --- the nested population --- *)
  let nested =
    List.mapi
      (fun i (sup, med) -> (string_of_int i, sup, med))
      (nested_seeds ~seed:!seed
         (List.map (fun j -> j.text) media_jobs)
         (List.map snd supports_jobs))
  in

  if !population_only then (
    Fmt.pr
      "at_rule_conditions: %d media condition(s) over %d environment(s), %d \
       supports, %d container over %d host(s), %d nested, seed %d@."
      (List.length media_jobs) (List.length environments)
      (List.length supports_jobs)
      (List.length !container_jobs)
      (List.length hosts) (List.length nested) !seed;
    exit 0);

  if Option.is_some (Browser.getenv "CASCADE_NO_BROWSER") then
    Browser.skip "at_rule_conditions" "CASCADE_NO_BROWSER is set";
  let node =
    match Browser.node_binary () with
    | Some n -> n
    | None -> Browser.skip "at_rule_conditions" "no node"
  in
  let chrome =
    match Browser.chrome_binary () with
    | Some c -> c
    | None -> Browser.skip "at_rule_conditions" "no headless browser"
  in
  let script_dir = Filename.dirname Sys.executable_name in
  let work = Filename.get_temp_dir_name () // "cascade-at-rule-conditions" in
  (try Unix.mkdir work 0o755 with Unix.Unix_error (Unix.EEXIST, _, _) -> ());
  let jobs_file = work // "jobs.json" in
  let pair id text =
    Json.Obj [ ("id", Json.Str id); ("text", Json.Str text) ]
  in
  write_jobs jobs_file
    ~envs:
      (List.map
         (fun e ->
           Json.Obj
             [
               ("id", Json.Str e.env_id);
               ("flags", Json.Arr (List.map (fun f -> Json.Str f) e.flags));
             ])
         environments)
    ~media:(List.map (fun j -> pair j.id j.text) media_jobs)
    ~nested:
      (List.map
         (fun (id, sup, med) ->
           Json.Obj
             [
               ("id", Json.Str id);
               ("supports", Json.Str sup);
               ("media", Json.Str med);
             ])
         nested)
    ~supports:(List.map (fun (id, text) -> pair id text) supports_jobs)
    ~hosts_json:
      (List.map
         (fun h ->
           Json.Obj [ ("id", Json.Str h.host_id); ("style", Json.Str h.style) ])
         hosts)
    ~container:(List.map (fun (id, text) -> pair id text) !container_jobs);
  let started = Unix.gettimeofday () in
  let lines =
    match
      run_driver ~node ~chrome
        ~script:(script_dir // "at_rule_conditions.js")
        ~jobs:jobs_file ~work
    with
    | Ok lines -> lines
    | Error err ->
        prerr_endline
          (String.concat ""
             [ "at_rule_conditions: the browser driver failed:\n"; err ]);
        exit 1
  in
  let elapsed = Unix.gettimeofday () -. started in
  parse_driver_output lines;
  List.iter
    (fun (scope, message) ->
      fail (String.concat "" [ "the page failed in "; scope; ": "; message ]))
    !driver_errors;

  (* --- the environments, as the browser reported them --- *)
  let contexts =
    List.map
      (fun e ->
        let features = table_of_env e.env_id in
        let media_inapplicable =
          List.filter_map
            (fun (name, value) ->
              if String.equal value "-" then Some (Media.name_of_string name)
              else None)
            (env_reading e.env_id)
        in
        ( e,
          features,
          Context.query ~media_type:"screen" ~media_features:features
            ~media_inapplicable () ))
      environments
  in
  List.iter
    (fun (e, features, _) ->
      if List.length features < 8 then
        fail
          (String.concat ""
             [
               "environment ";
               e.env_id;
               " reported ";
               string_of_int (List.length features);
               " features, so the browser was not asked what it is";
             ]);
      List.iter
        (fun (feature, value) ->
          notes :=
            String.concat ""
              [
                "environment ";
                e.env_id;
                " reports more than one keyword for ";
                feature;
                ": ";
                value;
                "; a query context holds one value per feature, so a threshold \
                 feature cannot be stood for";
              ]
            :: !notes)
        (thresholds e.env_id))
    contexts;

  (* --- evaluation --- *)
  let observations = ref 0 in
  let true_somewhere = Hashtbl.create 1024 in
  let disagreed = Hashtbl.create 256 in
  List.iter
    (fun (e, _, ctx) ->
      let where = String.concat "" [ "env "; e.env_id ] in
      List.iter
        (fun job ->
          match Hashtbl.find_opt media_answers (e.env_id, job.id) with
          | None ->
              fail
                (String.concat ""
                   [
                     "the browser did not answer about ";
                     job.text;
                     " in environment ";
                     e.env_id;
                   ])
          | Some answer -> (
              incr observations;
              if answer.primary then Hashtbl.replace true_somewhere job.id ();
              let cascade =
                match job.query with
                | None -> false
                | Some q -> (
                    match Context.matches_media ctx q with
                    | exception _ -> false
                    | b -> b)
              in
              let cascade =
                if planted "evaluation" (String.equal job.text "screen") then
                  not cascade
                else cascade
              in
              match judge ~cascade answer with
              | Agree -> ()
              | Split ->
                  splits :=
                    {
                      where;
                      what = job.text;
                      detail =
                        String.concat ""
                          [
                            "matchMedia ";
                            string_of_bool answer.primary;
                            ", the rule ";
                            string_of_bool answer.applied;
                          ];
                    }
                    :: !splits
              | Disagree ->
                  Hashtbl.replace disagreed job.text ();
                  evaluation :=
                    {
                      where;
                      what = job.text;
                      detail =
                        String.concat ""
                          [
                            "cascade ";
                            string_of_bool cascade;
                            ", the browser ";
                            string_of_bool answer.primary;
                          ];
                    }
                    :: !evaluation))
        media_jobs)
    contexts;

  (* --- rewriting --- *)
  List.iter
    (fun (label, before, after) ->
      List.iter
        (fun (e, _, _) ->
          match
            ( Hashtbl.find_opt media_answers (e.env_id, before),
              Hashtbl.find_opt media_answers (e.env_id, after) )
          with
          | Some a, Some b ->
              let differ =
                (not (Bool.equal a.primary b.primary))
                || planted "rewrite"
                     (String.equal (media_text before)
                        "(min-width: 400px) and (max-width: 800px)")
              in
              if differ then
                rewriting :=
                  {
                    where = String.concat "" [ "env "; e.env_id ];
                    what = String.concat "" [ label; ": "; media_text before ];
                    detail =
                      String.concat ""
                        [
                          "becomes ";
                          media_text after;
                          "; the browser says ";
                          string_of_bool a.primary;
                          " before and ";
                          string_of_bool b.primary;
                          " after";
                        ];
                  }
                  :: !rewriting
          | _ -> ())
        contexts)
    rewrite_pairs;

  (* --- merging --- *)
  (* [Media.equal] is structural equality on normalised queries, so two queries
     it calls equal serialise their normal forms alike. Bucketing by that
     serialisation is a superset of the equality classes, and the pairs inside
     one bucket are the only ones worth asking [equal] about. *)
  let buckets = Hashtbl.create 1024 in
  List.iter
    (fun job ->
      match job.query with
      | None -> ()
      | Some q -> (
          match Media.to_string ~minify:true (Media.normalize q) with
          | exception _ -> ()
          | key ->
              let previous =
                match Hashtbl.find_opt buckets key with
                | Some l -> l
                | None -> []
              in
              Hashtbl.replace buckets key (job :: previous)))
    media_jobs;
  let answer_vector job =
    let buf = Buffer.create (List.length environments) in
    List.iter
      (fun (e, _, _) ->
        Buffer.add_char buf
          (match Hashtbl.find_opt media_answers (e.env_id, job.id) with
          | Some a -> if a.primary then '1' else '0'
          | None -> '?'))
      contexts;
    let vector = Buffer.contents buf in
    if planted "merge" (String.equal job.text "(min-width: 400px)") then
      String.map (fun c -> if Char.equal c '0' then '1' else '0') vector
    else vector
  in
  let merge_pairs = ref 0 in
  Hashtbl.iter
    (fun normal members ->
      (* Bucketing by the normal form is a superset of the equality classes, so
         the members are partitioned by [Media.equal] before their answers are
         compared. *)
      let classes = ref [] in
      List.iter
        (fun job ->
          match job.query with
          | None -> ()
          | Some q ->
              let rec place = function
                | [] -> classes := ref [ job ] :: !classes
                | c :: rest -> (
                    match !c with
                    | { query = Some r; _ } :: _ when Media.equal r q ->
                        c := job :: !c
                    | _ -> place rest)
              in
              place !classes)
        members;
      List.iter
        (fun c ->
          let members = List.rev !c in
          let n = List.length members in
          merge_pairs := !merge_pairs + (n * (n - 1) / 2);
          let vectors = Hashtbl.create 4 in
          let order = ref [] in
          List.iter
            (fun job ->
              let v = answer_vector job in
              match Hashtbl.find_opt vectors v with
              | None ->
                  order := v :: !order;
                  Hashtbl.replace vectors v [ job.text ]
              | Some l -> Hashtbl.replace vectors v (job.text :: l))
            members;
          if Hashtbl.length vectors > 1 then
            merge_splits :=
              {
                normal;
                groups =
                  List.rev_map
                    (fun v ->
                      ( v,
                        match Hashtbl.find_opt vectors v with
                        | Some l -> List.rev l
                        | None -> [] ))
                    !order;
              }
              :: !merge_splits)
        !classes)
    buckets;

  (* --- supports --- *)
  let supports_table =
    List.filter_map
      (fun (id, text) ->
        match (Hashtbl.find_opt supports_answers id, parse_supports text) with
        | Some a, Some c when a.primary && supports_leaf c -> Some c
        | _ -> None)
      supports_jobs
  in
  let supports_ctx = Context.query ~supports:supports_table () in
  let supports_cascade text =
    match parse_supports text with
    | None -> false
    | Some c -> (
        match Context.matches_supports supports_ctx c with
        | exception _ -> false
        | b -> b)
  in
  List.iter
    (fun (id, text) ->
      match Hashtbl.find_opt supports_answers id with
      | None ->
          fail
            (String.concat ""
               [ "the browser did not answer about @supports "; text ])
      | Some answer -> (
          let cascade = supports_cascade text in
          match judge ~cascade answer with
          | Agree -> ()
          | Split ->
              splits :=
                {
                  where = "@supports";
                  what = text;
                  detail =
                    String.concat ""
                      [
                        "CSS.supports ";
                        string_of_bool answer.primary;
                        ", the rule ";
                        string_of_bool answer.applied;
                      ];
                }
                :: !splits
          | Disagree ->
              evaluation :=
                {
                  where = "@supports";
                  what = text;
                  detail =
                    String.concat ""
                      [
                        "cascade ";
                        string_of_bool cascade;
                        ", the browser ";
                        string_of_bool answer.primary;
                      ];
                }
                :: !evaluation))
    supports_jobs;

  (* [simplify_under] claims a decision that holds for every user agent, so one
     browser can only refute it. The arms below are the three refutations a
     single agent can carry, and each needs the context to be true in it. *)
  let supports_truth text =
    match Hashtbl.find_opt supports_ids text with
    | None -> None
    | Some id -> (
        match Hashtbl.find_opt supports_answers id with
        | Some a -> Some a.primary
        | None -> None)
  in
  let simplify_checked = ref 0 in
  List.iter
    (fun (k, c, decision) ->
      match (supports_truth k, supports_truth c) with
      | Some true, Some bc ->
          incr simplify_checked;
          let violation =
            match decision with
            | `True ->
                if bc then None
                else
                  Some
                    "cascade splices the block in as always guarded, and the \
                     browser says the guard is false where the context holds"
            | `False ->
                if bc then
                  Some
                    "cascade drops the block as unreachable, and the browser \
                     says both the context and the guard hold"
                else None
            | `Cond c' -> (
                match Supports.to_string c' with
                | exception _ -> None
                | text -> (
                    match supports_truth text with
                    | Some bc' when not (Bool.equal bc bc') ->
                        Some
                          (String.concat ""
                             [
                               "cascade narrows the guard to ";
                               text;
                               ", and the browser answers ";
                               string_of_bool bc';
                               " to that and ";
                               string_of_bool bc;
                               " to the original";
                             ])
                    | _ -> None))
          in
          Option.iter
            (fun detail ->
              evaluation :=
                {
                  where = "simplify_under";
                  what = String.concat "" [ c; "  under  "; k ];
                  detail;
                }
                :: !evaluation)
            violation
      | _ -> ())
    !simplify_sample;

  (* --- container --- *)
  let container_observations = ref 0 in
  List.iter
    (fun h ->
      let features =
        List.concat
          [
            [
              Container.feature "width" (Media.Length (Values.Px h.width));
              Container.feature "inline-size" (Media.Length (Values.Px h.width));
            ];
            (match h.height with
            | None -> []
            | Some height ->
                [
                  Container.feature "height" (Media.Length (Values.Px height));
                  Container.feature "block-size"
                    (Media.Length (Values.Px height));
                  Container.feature "orientation"
                    (Media.Ident
                       (if h.width >= height then Media.Landscape
                        else Media.Portrait));
                  Container.feature "aspect-ratio"
                    (Media.Ratio (int_of_float h.width, int_of_float height));
                ]);
            List.map (fun (name, value) -> Container.style ~value name) h.props;
          ]
      in
      let ctx =
        Context.query ~container_name:h.container_name
          ~container_features:features ()
      in
      List.iter
        (fun (id, text) ->
          match Hashtbl.find_opt container_answers (h.host_id, id) with
          | None ->
              fail
                (String.concat ""
                   [
                     "the browser did not answer about @container ";
                     text;
                     " for host ";
                     h.host_id;
                   ])
          | Some browser ->
              incr container_observations;
              let cascade =
                match parse_container text with
                | None -> false
                | Some c -> (
                    match Context.matches_container ctx c with
                    | exception _ -> false
                    | b -> b)
              in
              if not (Bool.equal cascade browser) then
                evaluation :=
                  {
                    where = String.concat "" [ "@container host "; h.host_id ];
                    what = text;
                    detail =
                      String.concat ""
                        [
                          "cascade ";
                          string_of_bool cascade;
                          ", the browser ";
                          string_of_bool browser;
                          "; the container is ";
                          h.style;
                        ];
                  }
                  :: !evaluation)
        !container_jobs)
    hosts;
  List.iter
    (fun (before, after, text) ->
      List.iter
        (fun h ->
          match
            ( Hashtbl.find_opt container_answers (h.host_id, before),
              Hashtbl.find_opt container_answers (h.host_id, after) )
          with
          | Some x, Some y when not (Bool.equal x y) ->
              rewriting :=
                {
                  where = String.concat "" [ "@container host "; h.host_id ];
                  what =
                    String.concat ""
                      [ "lower_for_minify: "; container_text before ];
                  detail =
                    String.concat ""
                      [
                        "becomes ";
                        text;
                        "; the browser says ";
                        string_of_bool x;
                        " before and ";
                        string_of_bool y;
                        " after";
                      ];
                }
                :: !rewriting
          | _ -> ())
        hosts)
    container_rewrites;

  (* --- nesting --- *)
  List.iter
    (fun (e, _, ctx) ->
      List.iter
        (fun (id, sup, med) ->
          match Hashtbl.find_opt nested_answers (e.env_id, id) with
          | None -> ()
          | Some browser ->
              let cascade =
                match parse_media med with
                | None -> false
                | Some mc -> (
                    match Context.matches_media ctx mc with
                    | exception _ -> false
                    | b -> b && supports_cascade sup)
              in
              if not (Bool.equal cascade browser) then
                evaluation :=
                  {
                    where = String.concat "" [ "nested env "; e.env_id ];
                    what =
                      String.concat ""
                        [ "@supports "; sup; " { @media "; med; " }" ];
                    detail =
                      String.concat ""
                        [
                          "cascade ";
                          string_of_bool cascade;
                          ", the browser ";
                          string_of_bool browser;
                        ];
                  }
                  :: !evaluation)
        nested)
    contexts;

  (* --- what the run asked --- *)
  Fmt.pr
    "at_rule_conditions: %d media condition(s) x %d environment(s) = %d \
     observation(s), seed %d, %.1fs@."
    (List.length media_jobs) (List.length environments) !observations !seed
    elapsed;
  Fmt.pr
    "  %d supports condition(s), %d simplify_under decision(s) the browser can \
     refute, %d container observation(s) over %d host(s), %d nested@."
    (List.length supports_jobs)
    !simplify_checked !container_observations (List.length hosts)
    (List.length nested);
  Fmt.pr "  %d media condition(s) hold somewhere, %d pair(s) cascade merges@."
    (Hashtbl.length true_somewhere)
    !merge_pairs;
  (* A merge finding names its environments by position in this list, so the
     list has to be printed for the vector to be readable. *)
  List.iter (fun (e, _, _) -> Fmt.pr "  env %s: %s@." e.env_id e.label) contexts;
  List.iter
    (fun (feature, value) -> Fmt.pr "  environment 0: %s = %s@." feature value)
    (env_reading "0");
  List.iter (fun n -> Fmt.pr "  note: %s@." n) (List.rev !notes);
  List.iter
    (fun text ->
      match Hashtbl.find_opt media_ids text with
      | None ->
          fail
            (String.concat ""
               [
                 "the anchor ";
                 text;
                 " left the population, so a green run proves less";
               ])
      | Some _ ->
          Fmt.pr "  anchor: %s -> %s@." text
            (if Hashtbl.mem disagreed text then "DISAGREED" else "agreed"))
    anchors;

  (match !only with
  | Some _ -> ()
  | None ->
      if List.length media_jobs < minimum_media then
        fail
          (String.concat ""
             [
               "the generator yielded ";
               string_of_int (List.length media_jobs);
               " media conditions, fewer than the ";
               string_of_int minimum_media;
               " expected";
             ]);
      if List.length environments < minimum_environments then
        fail "the environment list shrank below what a boundary needs";
      if !observations < minimum_media_observations then
        fail
          (String.concat ""
             [
               "only ";
               string_of_int !observations;
               " media observations, fewer than the ";
               string_of_int minimum_media_observations;
               " expected";
             ]);
      if List.length supports_jobs < minimum_supports then
        fail "the supports population shrank";
      if !container_observations < minimum_container_observations then
        fail "the container population shrank";
      (* A population of nothing but conditions that never hold agrees about all
         of it and asks nothing. *)
      if Hashtbl.length true_somewhere < minimum_true_media then
        fail
          (String.concat ""
             [
               "only ";
               string_of_int (Hashtbl.length true_somewhere);
               " media conditions hold in any environment, fewer than the ";
               string_of_int minimum_true_media;
               " expected";
             ]));

  report "EVALUATION (cascade and the browser disagree that the block applies)"
    !evaluation;
  report "REWRITING (a rewrite changed which media the query selects)"
    !rewriting;
  report_merging ();
  report "ORACLE SPLIT (the two browser oracles disagree)" !splits;
  let found =
    List.length !evaluation + List.length !rewriting + List.length !merge_splits
    + List.length !splits
  in
  if found > 0 || !failures > 0 then exit 1
