(* Does cascade agree with a browser about which at-rule conditions apply?

   [@media], [@supports] and [@container] preludes decide whether a whole block
   applies. Cascade answers that question in [Context.matches_media],
   [Context.matches_supports] and [Context.matches_container]; it answers a
   second one, whether two conditions mean the same thing, in [Media.equal] and
   [Container.equal], which gate block merging, and in [Media.lower_for_minify],
   which rewrites a prelude under minify. A wrong answer to either silently
   includes or excludes a whole block, and nothing was checking either against a
   browser.

   The questions are asked apart.

   Evaluation. The environment is not assumed: the page reads back what the
   browser says it is - the viewport, the resolution, and every discrete feature
   it recognises - and the query context cascade is asked about is built out of
   that reading. A plain feature the reading supplies is definitionally agreed;
   what the population is for is everything above it, the ranges, the negations,
   the [and]/[or] chains, the comma lists, the media types, the boolean forms
   and the features no browser recognises.

   Rewriting. [Media.lower_for_minify] and [Media.normalize] claim to preserve
   which media a query selects. That claim is checked without cascade evaluating
   anything: the browser answers the query as written and as rewritten, in every
   environment, and the two answers have to be one answer.

   Merging. [Media.equal] is documented as "true only when [a] and [b] select
   the same media", and it gates block merging. So for every pair it calls equal
   the browser must give one answer in every environment. An environment sits at
   each boundary the population names, and on both sides of it, because that is
   where an off-by-one lives.

   Two independent oracles answer each condition, as test/spec/browser's runs
   ask them: [matchMedia] and an [@media] rule that sets a custom property the
   probe's computed style is read for. A condition they disagree about is a fact
   about the browser rather than about cascade, and is reported rather than
   decided.

   Skips cleanly, with status 0, when node or a headless Chromium is missing.

   Reproducing one finding:

   dune exec test/render/at_rule_conditions.exe -- --only '(monochrome)' dune
   exec test/render/at_rule_conditions.exe -- --seed 3

   Showing the run is not blind:

   dune exec test/render/at_rule_conditions.exe -- --plant evaluation dune exec
   test/render/at_rule_conditions.exe -- --plant rewrite dune exec
   test/render/at_rule_conditions.exe -- --plant merge *)

