    "usage: at_rule_conditions [--seed N] [--only SUBSTRING] [--population] \
     [--plant evaluation|rewrite|merge]@.";
  exit 0

let parse_args () =
  let rec loop i =
    if i >= Array.length Sys.argv then ()
    else
      match Sys.argv.(i) with
      | "--seed" when i + 1 < Array.length Sys.argv ->
          seed := int_of_string Sys.argv.(i + 1);
          loop (i + 2)
      | "--only" when i + 1 < Array.length Sys.argv ->
          only := Some Sys.argv.(i + 1);
          loop (i + 2)
      | "--population" ->
          population_only := true;
          loop (i + 1)
      | "--plant" when i + 1 < Array.length Sys.argv ->
          plant := Some Sys.argv.(i + 1);
          loop (i + 2)
      | _ -> usage ()
  in
  loop 1

(* A wrong answer put into the comparison by hand, so a green run can be shown
   not to be a blind one. Each plant is one condition, so the report it produces
   is the report a real difference would produce. *)
let planted kind at =
  match !plant with Some k -> String.equal k kind && at | None -> false

let contains haystack needle =
  let n = String.length needle and h = String.length haystack in
  let rec at i =
    i + n <= h && (String.equal (String.sub haystack i n) needle || at (i + 1))
  in
  n = 0 || at 0

let selected text =
  match !only with None -> true | Some needle -> contains text needle

