(* ===== What a job may say ===== *)

(* A condition has to survive being written into a stylesheet, so anything
   carrying the sheet's own punctuation is not a condition this run can ask
   about. *)
let writable text =
  (not (String.equal text ""))
  && String.length text <= 400
  && not
       (String.exists
          (fun c ->
            Char.equal c ';' || Char.equal c '{' || Char.equal c '}'
            || Char.equal c '\n' || Char.equal c '\r' || Char.equal c '\\')
          text)

(* An empty media query list is a query, so the media population is the one
   place the empty text is a member rather than a gap. *)
let writable_media text = String.equal text "" || writable text

(* ===== The driver ===== *)

let read_lines ic =
  let rec loop acc =
    match input_line ic with
    | line -> loop (line :: acc)
    | exception End_of_file -> List.rev acc
  in
  loop []

let run_driver ~node ~chrome ~script ~jobs ~work =
  let errors = work // "at-rule-conditions.err" in
  let cmd =
    String.concat " "
      [
        String.concat "" [ "CHROME="; Filename.quote chrome ];
        Filename.quote node;
        Filename.quote script;
        Filename.quote jobs;
        Filename.quote work;
        String.concat "" [ "2>"; Filename.quote errors ];
      ]
  in
  let ic = Unix.open_process_in cmd in
  let lines = read_lines ic in
  match Unix.close_process_in ic with
  | Unix.WEXITED 0 -> Ok lines
  | Unix.WEXITED _ | Unix.WSIGNALED _ | Unix.WSTOPPED _ ->
      let ic = open_in errors in
      let text = read_lines ic in
      close_in ic;
      Error (String.concat "\n" text)

(* ===== The browser's answers ===== *)

type answer = { primary : bool; applied : bool }

let discovered : (string * string, string) Hashtbl.t = Hashtbl.create 512
let media_answers : (string * string, answer) Hashtbl.t = Hashtbl.create 65536
let nested_answers : (string * string, bool) Hashtbl.t = Hashtbl.create 4096
let supports_answers : (string, answer) Hashtbl.t = Hashtbl.create 1024
let container_answers : (string * string, bool) Hashtbl.t = Hashtbl.create 4096
let driver_errors : (string * string) list ref = ref []
let bit s = String.equal s "1"

let parse_driver_output lines =
  List.iter
    (fun line ->
      match String.split_on_char '\t' line with
      | [ "e"; env; feature; value ] ->
          Hashtbl.replace discovered (env, feature) value
      | [ "m"; env; id; primary; applied ] ->
          Hashtbl.replace media_answers (env, id)
            { primary = bit primary; applied = bit applied }
      | [ "n"; env; id; applied ] ->
          Hashtbl.replace nested_answers (env, id) (bit applied)
      | [ "s"; id; primary; applied ] ->
          Hashtbl.replace supports_answers id
            { primary = bit primary; applied = bit applied }
      | [ "c"; host; id; applied ] ->
          Hashtbl.replace container_answers (host, id) (bit applied)
      | "x" :: scope :: rest ->
          driver_errors := (scope, String.concat "\t" rest) :: !driver_errors
      | _ -> ())
    lines

(* ===== The query context, built out of what the browser reported ===== *)

(* "?" is unknown; "-" is recognized but matches no value. Keep these states
   distinct in the explicit context, since negation distinguishes them. A
   feature reporting multiple keywords is a threshold feature; the first value
   is taken and the reading is reported. *)
let env_reading env =
  let entries =
    Hashtbl.fold
      (fun (e, feature) value acc ->
        if String.equal e env then (feature, value) :: acc else acc)
      discovered []
  in
  List.sort (fun (a, _) (b, _) -> String.compare a b) entries

let table_of_env env =
  List.filter_map
    (fun (feature, value) ->
      if String.equal value "?" || String.equal value "-" then None
      else
        let value =
          match String.index_opt value ',' with
          | Some i -> String.sub value 0 i
          | None -> value
        in
        match Media.feature feature (Media.value_of_string value) with
        | exception _ -> None
        | entry -> Some entry)
    (env_reading env)

let thresholds env =
  List.filter (fun (_, value) -> String.contains value ',') (env_reading env)

(* ===== Parsing, guarded ===== *)

type media_job = { id : string; text : string; query : Media.t option }

let parse_media text =
  match Media.of_string text with exception _ -> None | q -> Some q

let parse_supports text =
  match Supports.of_string text with exception _ -> None | c -> Some c

let parse_container text =
  match Container.of_string text with exception _ -> None | c -> Some c

let supports_leaf (c : Supports.t) =
  match c with Property _ | Function _ -> true | Not _ | And _ | Or _ -> false

(* A rewrite is checked by asking the browser about the rewritten text, so the
   rewrite joins the population. Reading the query back out of the parser is a
   stage of its own, and the first one: a query the parser recovers to [not all]
   has already lost what it selected before any rewrite runs, and attributing
   that to the rewrite would name the wrong function. *)
let serialise q =
  match Media.to_string ~minify:true q with
  | exception _ -> None
  | text -> Some text

let rewrites_of = function
  | None -> []
  | Some q ->
      List.filter_map
        (fun (label, rewritten) ->
          Option.map (fun text -> (label, text)) (serialise rewritten))
        [
          ("round_trip", q);
          ("lower_for_minify", Media.lower_for_minify q);
          ("normalize", Media.normalize q);
        ]

(* ===== Judging ===== *)

type verdict = Agree | Disagree | Split

let judge ~cascade answer =
  if not (Bool.equal answer.primary answer.applied) then Split
  else if Bool.equal cascade answer.primary then Agree
  else Disagree

let verdict_name = function
  | Agree -> "agree"
  | Disagree -> "disagree"
  | Split -> "split"

(* The judge decides nothing about a condition, so putting made-up verdicts
   through it says whether the arm that reports a difference can fire at all. A
   run that reports nothing has to be a run that could have. *)
let check_judge () =
  let cases =
    [
      ("both say yes", true, { primary = true; applied = true }, "agree");
      ("both say no", false, { primary = false; applied = false }, "agree");
      ( "only the browser says yes",
        false,
        { primary = true; applied = true },
        "disagree" );
      ( "only cascade says yes",
        true,
        { primary = false; applied = false },
        "disagree" );
      ( "the oracles disagree",
        true,
        { primary = true; applied = false },
        "split" );
    ]
  in
  List.iter
    (fun (what, cascade, answer, expected) ->
      let got = verdict_name (judge ~cascade answer) in
      if not (String.equal got expected) then (
        Fmt.pr "FAIL the judge calls %s %s, not %s@." what got expected;
        exit 1))
    cases

(* ===== Findings ===== *)

type finding = { where : string; what : string; detail : string }

(* A merge finding is a whole equivalence class, not a pair: cascade calls the
   members one query, so what a browser that tells them apart produces is a
   partition of the class, and printing that once says more than printing every
   pair of it. *)
type merge_split = { normal : string; groups : (string * string list) list }

let evaluation : finding list ref = ref []
let rewriting : finding list ref = ref []
let merge_splits : merge_split list ref = ref []
let splits : finding list ref = ref []
let notes : string list ref = ref []
let failures = ref 0

let fail line =
  incr failures;
  Fmt.pr "FAIL %s@." line

(* One condition that comes out differently in six environments is one finding
   seen six times, so the environments are gathered onto the line rather than
   printed as six of them. *)
let report label findings =
  match findings with
  | [] -> ()
  | _ ->
      let table = Hashtbl.create 256 in
      let order = ref [] in
      List.iter
        (fun f ->
          let key = (f.what, f.detail) in
          match Hashtbl.find_opt table key with
          | None ->
              order := key :: !order;
              Hashtbl.replace table key [ f.where ]
          | Some l -> Hashtbl.replace table key (f.where :: l))
        (List.rev findings);
      Fmt.pr "@.%s: %d over %d distinct condition(s)@." label
        (List.length findings) (List.length !order);
      List.iter
        (fun (what, detail) ->
          let wheres =
            match Hashtbl.find_opt table (what, detail) with
            | Some l -> List.rev l
            | None -> []
          in
          Fmt.pr "  %s | %s | %s@." what detail (String.concat ", " wheres))
        (List.rev !order)

let report_merging () =
  match !merge_splits with
  | [] -> ()
  | found ->
      Fmt.pr
        "@.MERGING (cascade merges blocks the browser tells apart): %d \
         equivalence class(es)@."
        (List.length found);
      List.iter
        (fun split ->
          Fmt.pr "  class %s@." split.normal;
          List.iter
            (fun (vector, members) ->
              Fmt.pr "    %s : %s@." vector (String.concat " | " members))
            split.groups)
        (List.rev found)

